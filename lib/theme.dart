class PalScope extends InheritedWidget {
  final Pal pal;
  const PalScope({super.key, required this.pal, required super.child});
  static Pal of(BuildContext c) => c.dependOnInheritedWidgetOfExactType<PalScope>()!.pal;
  @override
  bool updateShouldNotify(PalScope old) => old.pal != pal;
}

extension PalX on BuildContext {
  Pal get pal => PalScope.of(this);
}

/// Seven-segment display font.
TextStyle lcd(double size, Color c) =>
    TextStyle(fontFamily: 'DSEG7', fontSize: size, height: 1, color: c, letterSpacing: 0);

/// Geist Mono (variable font) at a given weight.
TextStyle mono(double size, Color c, {double weight = 400, double ls = 0, double? height}) => TextStyle(
  fontFamily: 'GeistMono',
  fontSize: size,
  color: c,
  letterSpacing: ls,
  height: height,
  fontVariations: [FontVariation('wght', weight)],
  fontWeight: weight >= 600 ? FontWeight.w600 : (weight >= 500 ? FontWeight.w500 : FontWeight.w400),
);
